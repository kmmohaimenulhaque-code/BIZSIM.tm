#!/usr/bin/env python3
"""Download each built-in season's Wikipedia cover (listed in shared/seasonImages.js),
shrink it to a 800px WebP and store it in client/public/covers/, so covers load
instantly and offline on every platform, including the phone apps.
Run after scripts/build-images.mjs:  python3 scripts/bundle-covers.py"""
import io, json, os, re, sys, time, urllib.request
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'shared', 'seasonImages.js')
OUT = os.path.join(ROOT, 'client', 'public', 'covers')
os.makedirs(OUT, exist_ok=True)
text = open(SRC, encoding='utf-8').read()
data = json.loads(text[text.index('{'):text.rindex('}') + 1])
UA = "BIZSIM/1.5 (cover bundler; contact via github)"
ok = 0
for cid, img in data.items():
    if not img:
        continue
    dest = os.path.join(OUT, f'{cid}.webp')
    if not os.path.exists(dest):
        url = img.get('remote') or img['url']
        plain = url.split('?')[0]
        urls = [url, plain]
        m = re.match(r'(https://upload\.wikimedia\.org/wikipedia/[^/]+)/(\w/\w\w)/([^/]+)$', plain)
        if m:  # a standard-size thumbnail of the original
            urls.append(f'{m.group(1)}/thumb/{m.group(2)}/{m.group(3)}/500px-{m.group(3)}')
        for attempt in range(5):
            try:
                req = urllib.request.Request(urls[min(attempt, len(urls) - 1)], headers={'User-Agent': UA})
                raw = urllib.request.urlopen(req, timeout=40).read()
                im = Image.open(io.BytesIO(raw))
                im = im.convert('RGBA' if im.mode in ('RGBA', 'LA', 'P') else 'RGB')
                if im.mode == 'RGBA':  # flatten transparent logos and maps on white
                    bg = Image.new('RGB', im.size, (255, 255, 255))
                    bg.paste(im, mask=im.split()[3])
                    im = bg
                im.thumbnail((800, 800), Image.LANCZOS)
                im.save(dest, 'WEBP', quality=72, method=6)
                break
            except Exception as e:  # noqa: BLE001
                if attempt == 4:
                    print('FAILED', cid, e, file=sys.stderr)
                time.sleep(3 * (attempt + 1))
        time.sleep(0.4)
    if os.path.exists(dest):
        img.setdefault('remote', img['url'])
        img['url'] = f'/covers/{cid}.webp'
        w, h = Image.open(dest).size
        img['width'], img['height'] = w, h
        ok += 1
body = ('// Generated by scripts/build-images.mjs and scripts/bundle-covers.py. Do not edit by hand.\n'
        '// Cover image for each built-in season: the lead image of its own Wikipedia\n'
        '// article, free licences only (null when the article has none). `url` is the\n'
        '// copy bundled with the app; `remote` is the Wikimedia original.\n'
        'export const SEASON_IMAGES = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
open(SRC, 'w', encoding='utf-8').write(body)
size = sum(os.path.getsize(os.path.join(OUT, f)) for f in os.listdir(OUT))
print(f'{ok} covers bundled, {size/1e6:.1f} MB')
