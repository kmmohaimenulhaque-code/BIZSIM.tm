// Regenerates shared/seasons/extras/index.js from the x*.js files in that folder.
import { readdirSync, writeFileSync } from 'node:fs';
const dir = new URL('../shared/seasons/extras/', import.meta.url);
const files = readdirSync(dir).filter((f) => /^x\d+\.js$/.test(f)).sort();
const names = files.map((f) => f.replace('.js', ''));
writeFileSync(
  new URL('index.js', dir),
  `// The extra decision and the insight for every episode, keyed by catalogue number.\n// Generated by scripts/extras-index.mjs.\n${names.map((n) => `import ${n} from './${n}.js';`).join('\n')}\n\nexport const EXTRAS = Object.assign({}, ${names.join(', ')});\n`,
);
console.log(`extras index: ${files.length} files`);
