// Pre-computes each built-in season's cover image: the lead image of the
// season's own Wikipedia article (free licences only). Run when seasons change:
//   node scripts/build-images.mjs
// Writes shared/seasonImages.js. Seasons whose article has no free lead image
// get null, and the app shows its typographic cover instead.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOGUE } from '../shared/catalogue.js';
import { wikiLeadImages } from '../shared/wikiImage.js';
import { CASE_BY_ID } from '../shared/cases/index.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const titles = [...new Set(CATALOGUE.map((e) => e.wiki))];
const found = {};
for (let i = 0; i < titles.length; i += 25) {
  const group = titles.slice(i, i + 25);
  for (let attempt = 0; ; attempt++) {
    try {
      Object.assign(found, await wikiLeadImages(group, 1280));
      break;
    } catch (e) {
      if (attempt >= 5) throw e;
      await new Promise((r) => setTimeout(r, 5000 * (attempt + 1)));
    }
  }
  await new Promise((r) => setTimeout(r, 1500));
}
// No free image on the main article: try the season's other cited articles, in order.
const altOf = (e) =>
  (CASE_BY_ID[e.caseId]?.sources || [])
    .filter((x) => /wikipedia\.org\/wiki\//.test(x.url || ''))
    .map((x) => decodeURIComponent(x.url.split('/wiki/')[1]).replace(/_/g, ' '))
    .filter((t) => t !== e.wiki);
const alts = [...new Set(CATALOGUE.filter((e) => !found[e.wiki]).flatMap(altOf))].filter((t) => !(t in found));
for (let i = 0; i < alts.length; i += 25) {
  Object.assign(found, await wikiLeadImages(alts.slice(i, i + 25), 1280).catch(() => ({})));
  await new Promise((r) => setTimeout(r, 1500));
}
const out = {};
for (const e of CATALOGUE) {
  const img = found[e.wiki] || altOf(e).map((t) => found[t]).find(Boolean) || null;
  out[e.caseId] = img && { url: img.url, title: img.title.length > 90 ? `${img.title.slice(0, 87)}...` : img.title, creator: img.creator, license: img.license, licenseUrl: img.licenseUrl, landingUrl: img.landingUrl, article: img.article, provider: img.provider };
}
const body = `// Generated by scripts/build-images.mjs. Do not edit by hand.
// Cover image for each built-in season: the lead image of its own Wikipedia
// article, free licences only (null when the article has none).
export const SEASON_IMAGES = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync(path.join(root, 'shared/seasonImages.js'), body);
const n = Object.values(out).filter(Boolean).length;
console.log(`${n} of ${CATALOGUE.length} seasons have a free Wikipedia image`);
