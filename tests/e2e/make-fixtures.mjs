import { CASE_BY_ID } from '../../shared/cases/index.js';
import { createPackage, packageToText, packageToFrames } from '../../shared/package.js';
import fs from 'node:fs';
const OUT = process.env.E2E_FIXTURES || '/tmp/bizsim-e2e';
fs.mkdirSync(`${OUT}/qr`, { recursive: true });
import { createRequire } from 'node:module';
const require = createRequire(new URL('../../package.json', import.meta.url));
const QRCode = require('qrcode');
const ai = structuredClone(CASE_BY_ID['season-c010']);
ai.id = 'gen-testco-e2e1'; ai.source = 'generated'; ai.model = 'mock-model'; ai.title = 'TestCo: An imported AI season'; ai.company = 'TestCo';
fs.writeFileSync(`${OUT}/ai.bizsim`, packageToText(createPackage(ai, { appVersion: '1.6.0' })));
const ai2 = structuredClone(ai); ai2.tagline = 'A changed version';
fs.writeFileSync(`${OUT}/ai2.bizsim`, packageToText(createPackage(ai2, { appVersion: '1.6.0' })));
fs.writeFileSync(`${OUT}/curated.bizsim`, packageToText(createPackage(CASE_BY_ID['season-c001'], { appVersion: '1.6.0' })));
const bad = JSON.parse(packageToText(createPackage(ai))); bad.content.case.title = 'tampered'; fs.writeFileSync(`${OUT}/tampered.bizsim`, JSON.stringify(bad));
const ep = structuredClone(CASE_BY_ID['season-c030']); ep.id='chat-qrseason-e2e'; ep.source='chat'; ep.model='mock'; ep.title='QR Season via codes';
const frames = packageToFrames(createPackage(ep, { episode: 1 }));
for (const [i, f] of frames.entries()) await QRCode.toFile(`${OUT}/qr/f${String(i).padStart(2,'0')}.png`, f, { errorCorrectionLevel: 'M', margin: 2, width: 600 });
console.log('frames', frames.length);
fs.writeFileSync(`${OUT}/badbackup.json`, '{"app":"BIZSIM","version":7}');
